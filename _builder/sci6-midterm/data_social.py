def grp(title, ctx, ctxSay, bank=None, img=None, alt="", readEach=True):
    g = {"title": title, "ctx": ctx, "ctxSay": Z(ctxSay), "readEach": readEach}
    g["once"] = True  # 題幹只在該組第一小題自動唸一次
    if img: g["img"] = img; g["alt"] = alt
    if bank:
        g["bank"] = bank
        nm = lambda c, w: f"{cs(c)}，{w}" if w else cs(c)
        g["bankSay"] = [["zh", nm(c, w) + "。"] for c, w in bank]
        g["pickSay"] = [f"你選的是{nm(c, w)}" for c, w in bank]
        g["onSay"] = [f"選了{nm(c, w)}" for c, w in bank]
        g["offSay"] = [f"取消{nm(c, w)}" for c, w in bank]
    return g

