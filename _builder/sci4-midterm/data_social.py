def grp(title, ctx, ctxSay, bank=None, img=None, alt="", readEach=True):
    g = {"title": title, "ctx": ctx, "ctxSay": Z(ctxSay), "readEach": readEach}
    if img: g["img"] = img; g["alt"] = alt
    if bank:
        g["bank"] = bank
        g["bankSay"] = [["zh", f"{c}，{w}。"] for c, w in bank]
        g["pickSay"] = [f"你選的是{c}，{w}" for c, w in bank]
        g["onSay"] = [f"選了{c}，{w}" for c, w in bank]
        g["offSay"] = [f"取消{c}，{w}" for c, w in bank]
    return g

